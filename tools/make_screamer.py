"""Generates mod/src/ap_screamer.h: the picture of the "Boys of Silence" trap.

    python tools/make_screamer.py [--variant full|head] [--source image] [--preview preview.png]

Default source: the Comstock House loading picture (S_DCom_P_Loading_SF.S_DCom_P_Loading.18-Com_House,
608x400 DXT1, in the package), showing three Boys of Silence under the spotlights.
  full: the whole picture;  head: the middle head, cropped, contrasted and vignetted.
--source: another picture (file) instead of the game's.
Output: BGRA 512x512 (stretched over the whole screen by the mod), zlib compressed (the mod
inflates it with miniz).
"""

from __future__ import annotations

import argparse
import pathlib
import struct
import zlib

from PIL import Image, ImageDraw, ImageEnhance, ImageFilter

from game import COOKED
from upk import Package

OUT = pathlib.Path(__file__).parent.parent / "mod" / "src" / "ap_screamer.h"
SIZE = 512
WIDTH, HEIGHT = 608, 400
HEAD_BOX = (248, 222, 372, 346)  # middle head, in the 608x400 picture


def rgb565(c: int) -> tuple[int, int, int]:
    return ((c >> 11) & 31) * 255 // 31, ((c >> 5) & 63) * 255 // 63, (c & 31) * 255 // 31


def decode_dxt1(data: bytes, width: int, height: int) -> Image.Image:
    image = Image.new("RGB", (width, height))
    px = image.load()
    o = 0
    for by in range(height // 4):
        for bx in range(width // 4):
            c0, c1, bits = struct.unpack_from("<HHI", data, o)
            o += 8
            a, b = rgb565(c0), rgb565(c1)
            if c0 > c1:
                colors = [
                    a,
                    b,
                    tuple((2 * x + y) // 3 for x, y in zip(a, b)),
                    tuple((x + 2 * y) // 3 for x, y in zip(a, b)),
                ]
            else:
                colors = [a, b, tuple((x + y) // 2 for x, y in zip(a, b)), (0, 0, 0)]
            for i in range(16):
                px[bx * 4 + i % 4, by * 4 + i // 4] = colors[(bits >> (2 * i)) & 3]
    return image


def loading_image() -> Image.Image:
    pkg = Package(str(COOKED / "S_DCom_P_Loading_SF.xxx"))
    exp = next(e for e in pkg.exports if pkg.class_of(e) == "Texture2D")
    raw = pkg.read(exp.serial_offset, exp.serial_size)
    size = (WIDTH // 4) * (HEIGHT // 4) * 8
    # Mip 0 data: chunk header (flags, count, size, position) then the pixels.
    for o in range(len(raw) - 16):
        _, count, length, _ = struct.unpack_from("<IIII", raw, o)
        if count == size and length == size:
            return decode_dxt1(raw[o + 16 : o + 16 + size], WIDTH, HEIGHT)
    raise SystemExit("mip 0 not found in the texture")


def head(image: Image.Image) -> Image.Image:
    crop = image.crop(HEAD_BOX).resize((SIZE, SIZE), Image.LANCZOS)
    crop = ImageEnhance.Brightness(ImageEnhance.Contrast(crop).enhance(1.5)).enhance(1.3)
    mask = Image.new("L", (SIZE, SIZE), 0)
    ImageDraw.Draw(mask).ellipse((20, 20, SIZE - 20, SIZE - 20), fill=255)
    return Image.composite(crop, Image.new("RGB", (SIZE, SIZE)), mask.filter(ImageFilter.GaussianBlur(56)))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--variant", choices=("full", "head"), default="full")
    parser.add_argument("--source")
    parser.add_argument("--preview")
    args = parser.parse_args()
    if args.source:
        out = Image.open(args.source).convert("RGB").resize((SIZE, SIZE), Image.LANCZOS)
        args.variant = pathlib.Path(args.source).name
    else:
        image = loading_image()
        out = head(image) if args.variant == "head" else image.resize((SIZE, SIZE), Image.LANCZOS)
    if args.preview:
        out.save(args.preview)
    bgra = bytearray()
    for r, g, b in out.convert("RGB").getdata():
        bgra += bytes((b, g, r, 255))
    packed = zlib.compress(bytes(bgra), 9)
    lines = [
        "#pragma once",
        "",
        f"// Picture of the \"Boys of Silence\" trap ({args.variant}), {SIZE}x{SIZE} BGRA, zlib compressed.",
        "// Generated by tools/make_screamer.py. Do not edit by hand.",
        "",
        "#include <cstdint>",
        "",
        "namespace bsap::screamer {",
        "",
        f"constexpr int kSize = {SIZE};",
        f"constexpr unsigned long kBgraBytes = {len(bgra)};",
        f"constexpr std::uint8_t kPacked[{len(packed)}] = {{",
    ]
    for i in range(0, len(packed), 24):
        lines.append("    " + ", ".join(f"0x{v:02X}" for v in packed[i : i + 24]) + ",")
    lines += ["};", "", "}  // namespace bsap::screamer", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{args.variant} -> {OUT} ({len(bgra)} bytes, {len(packed)} compressed)")


if __name__ == "__main__":
    main()
