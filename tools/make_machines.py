"""Generates apworld/bioshock_infinite/machines.py from tools/vending_catalog.json.

python tools/catalog_vending.py   # inventory of the game's packages
python tools/make_machines.py     # Dollar Bill table for the APWorld
"""

import json
import pathlib
from collections import defaultdict

HERE = pathlib.Path(__file__).parent
CATALOG = HERE / "vending_catalog.json"
OUT = HERE.parent / "apworld" / "bioshock_infinite" / "machines.py"

# Level package prefix -> game area, in story order.
AREAS = {
    "twn": "Town Center",
    "bw": "Battleship Bay",
    "fink": "Finkton",
    "emp": "Emporia",
    "chu": "Hand of the Prophet",
}


def main() -> None:
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    by_area: dict[str, list[str]] = defaultdict(list)
    for machine in catalog:
        # Dollar Bill = SP_ConsumableVendingMachine archetype (and its variants).
        if "ConsumableVendingMachine" not in machine["archetype"]:
            continue
        prefix = machine["package"].split("_")[1].lower()
        by_area[AREAS[prefix]].append(machine["path"])

    lines = [
        '"""All the Dollar Bill machines placed in the game. Generated by tools/make_machines.py."""',
        "",
        "# (area, number in the area, path of the object in the game: same as the mod's PathName)",
        "DOLLAR_BILLS: list[tuple[str, int, str]] = [",
    ]
    for area in AREAS.values():
        for number, path in enumerate(sorted(by_area[area], key=str.lower), start=1):
            lines.append(f'    ("{area}", {number}, "{path}"),')
    lines.append("]")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{sum(len(v) for v in by_area.values())} Dollar Bills -> {OUT}")


if __name__ == "__main__":
    main()
