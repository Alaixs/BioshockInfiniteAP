"""Inventory of the Infusion bottles placed in BioShock Infinite's levels.

    python tools/catalog_infusions.py

A bottle is an XLootContainerKActor (Outer = PersistentLevel) with the
"Pickup_UnstableTonic_Upgrades" archetype. They are all alike: the mod recognizes them by
"level package.object name" (S_TWN_Float_B_Loot.XLootContainerKActor_43).

The game doesn't name their place: the place (LocationFound) of the nearest placed Voxophone is used
if it is within NEAR units in the same area, otherwise the area alone. Writes
apworld/bioshock_infinite/infusions.py.

Excluded: the 5 bottles of the Blue Ribbon (S_TWN_Float_B_Loot), hidden at start (bStartHidden):
Season Pass bonus (AllSeasonPassInfusionsPickedUp), missing without it.
"""

from __future__ import annotations

import math
import pathlib

from catalog_voxophones import ALIASES, AREAS, PREFIX, ascii_text, recording_of, translations
from game import COOKED
from upk import Package

OUT = pathlib.Path(__file__).parent.parent / "apworld" / "bioshock_infinite" / "infusions.py"

INFUSION = "Pickup_UnstableTonic_Upgrades"
NEAR = 3000.0  # 30 m
SEASON_PASS = {"S_TWN_Float_B_Loot"}


def area_of(package: str) -> str:
    prefix = package.split("_")[1].lower()
    if prefix not in AREAS:
        raise SystemExit(f"unknown area for package {package}")
    return AREAS[prefix]


def scan() -> tuple[list[tuple[str, str, tuple]], list[tuple[str, str, tuple]]]:
    """(bottles, Voxophones): (area, id or place, position)."""
    names = translations()
    infusions, voxophones = [], []
    for f in sorted(COOKED.glob("S_*.xxx")):
        if f.stem in SEASON_PASS:
            continue
        try:
            pkg = Package(str(f))
        except Exception:
            continue
        if not any(n == INFUSION or n.startswith(PREFIX) for n in pkg.names):
            continue
        for exp in pkg.exports:
            try:
                archetype = pkg.archetype_of(exp) or ""
                path = pkg.path_of(exp, f.stem)
            except Exception:
                continue
            if ".PersistentLevel." not in path or not (archetype == INFUSION or archetype.startswith(PREFIX)):
                continue
            pos = pkg.properties(exp).get("XPrivateLocalLocation", (None, None))[1]
            if not isinstance(pos, tuple):
                print(f"  ! {path}: no position")
                continue
            if archetype == INFUSION:
                infusions.append((area_of(f.stem), f"{f.stem}.{path.rsplit('.', 1)[1]}", pos))
            else:
                recording = recording_of(pkg, exp) or archetype[len(PREFIX) :]
                info = names.get(ALIASES.get(recording, recording).lower(), {})
                place = ascii_text(info.get("LocationFound", ""))
                if place:
                    voxophones.append((area_of(f.stem), place, pos))
    return infusions, voxophones


def main() -> None:
    infusions, voxophones = scan()
    rows = []
    for area, ident, pos in infusions:
        near = [(math.dist(pos, vpos), place) for varea, place, vpos in voxophones if varea == area]
        distance, place = min(near, default=(math.inf, ""))
        rows.append((area, ident, place if distance <= NEAR else "", round(distance)))
    order = list(AREAS.values())
    rows.sort(key=lambda r: (order.index(r[0]), r[1].lower()))

    lines = [
        '"""All the Infusion bottles of the game. Generated by tools/catalog_infusions.py."""',
        "",
        '# (area, game id (package.object), place of the nearest Voxophone or "")',
        "INFUSIONS: list[tuple[str, str, str]] = [",
    ]
    for area, ident, place, distance in rows:
        lines.append(f"    {(area, ident, place)!r},  # Voxophone {distance / 100:.0f} m away")
    lines.append("]")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(rows)} Infusions -> {OUT}")


if __name__ == "__main__":
    main()
