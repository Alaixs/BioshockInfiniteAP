"""Generates mod/src/ap_emblem.h: the top of the login screen frame, with the Archipelago logo
instead of the star emblem.

    python tools/make_emblem.py [--preview preview.png]

The original picture is the game's XTwoKAccountMenu_I79 texture (808x128, DXT5), read from the
installed game's package. The logo (assets/logo_archi.png, cut out like the item icon) is placed
on the shield, of which only the tip shows below. Output: zlib compressed BGRA pixels (inflated by
the DLL with miniz).
"""

import argparse
import pathlib
import struct
import sys
import zlib

from PIL import Image

ROOT = pathlib.Path(__file__).parent.parent
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from game import COOKED  # noqa: E402
from make_icon import remove_black_background  # noqa: E402
from upk import Package  # noqa: E402

GAME_PACKAGE = str(COOKED / "XEntry_p.xxx")
TEXTURE = "XTwoKAccountMenu_I79"
LOGO = ROOT / "assets" / "logo_archi.png"
OUT = ROOT / "mod" / "src" / "ap_emblem.h"
LOGO_SIZE = 102  # the shield is about 80x78 px
LOGO_CENTER_X, LOGO_BOTTOM = 403, 126  # center of the shield; bottom of the logo in the texture (128 px)


def rgb565(c: int) -> tuple[int, int, int]:
    return ((c >> 11) & 31) * 255 // 31, ((c >> 5) & 63) * 255 // 63, (c & 31) * 255 // 31


def decode_dxt5(data: bytes, w: int, h: int) -> Image.Image:
    img = Image.new("RGBA", (w, h))
    px = img.load()
    o = 0
    for by in range(0, h, 4):
        for bx in range(0, w, 4):
            b = data[o : o + 16]
            o += 16
            a0, a1 = b[0], b[1]
            abits = int.from_bytes(b[2:8], "little")
            if a0 > a1:
                alphas = [a0, a1] + [((6 - i) * a0 + (i + 1) * a1) // 7 for i in range(6)]
            else:
                alphas = [a0, a1] + [((4 - i) * a0 + (i + 1) * a1) // 5 for i in range(4)] + [0, 255]
            c0, c1, idx = struct.unpack("<HHI", b[8:])
            p0, p1 = rgb565(c0), rgb565(c1)
            colors = [
                p0,
                p1,
                tuple((2 * a + b) // 3 for a, b in zip(p0, p1)),
                tuple((a + 2 * b) // 3 for a, b in zip(p0, p1)),
            ]
            for j in range(16):
                x, y = bx + j % 4, by + j // 4
                if x < w and y < h:
                    px[x, y] = colors[(idx >> (2 * j)) & 3] + (alphas[(abits >> (3 * j)) & 7],)
    return img


def game_texture(package: str, name: str) -> Image.Image:
    p = Package(package)
    exp = next(e for e in p.exports if e.name == name and p.class_of(e) == "Texture2D")
    data = p.read(exp.serial_offset, exp.serial_size)
    props = p.properties(exp)
    w, h = props["SizeX"][1], props["SizeY"][1]
    fmt = p.name(struct.unpack_from("<i", props["Format"][1])[0])
    if fmt != "PF_DXT5":
        raise SystemExit(f"{name}: unexpected format {fmt}")
    # After the properties (ending with "None"): mip count, then the first mip's header (flags,
    # element count, size on disk, position) and its data.
    none = struct.pack("<ii", p.names.index("None"), 0)
    o = data.find(none, 0x100) + 8
    _count, _flags, _elements, size, _offset = struct.unpack_from("<iIiii", data, o)
    return decode_dxt5(data[o + 20 : o + 20 + size], w, h)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--package", default=GAME_PACKAGE)
    parser.add_argument("--preview")
    args = parser.parse_args()

    frame = game_texture(args.package, TEXTURE)
    logo = remove_black_background(Image.open(LOGO))
    logo = logo.crop(logo.getbbox())
    logo.thumbnail((LOGO_SIZE, LOGO_SIZE), Image.LANCZOS)
    frame.alpha_composite(logo, (LOGO_CENTER_X - logo.width // 2, LOGO_BOTTOM - logo.height))
    if args.preview:
        frame.save(args.preview)

    r, g, b, a = frame.split()
    bgra = Image.merge("RGBA", (b, g, r, a)).tobytes()
    packed = zlib.compress(bgra, 9)
    lines = [packed[i : i + 32] for i in range(0, len(packed), 32)]
    body = ",\n".join("    " + ", ".join(f"0x{v:02X}" for v in line) for line in lines)
    OUT.write_text(
        "#pragma once\n\n"
        "// Generated by tools/make_emblem.py: top of the login screen frame (game texture\n"
        "// XTwoKAccountMenu_I79) with the Archipelago logo instead of the star emblem.\n"
        "// BGRA pixels (PF_A8R8G8B8), zlib compressed.\n\n"
        "#include <cstdint>\n\n"
        "namespace bsap::emblem {\n\n"
        f"constexpr int kWidth = {frame.width};\n"
        f"constexpr int kHeight = {frame.height};\n"
        f"constexpr unsigned char kBgraZlib[] = {{\n{body}\n}};\n\n"
        "}  // namespace bsap::emblem\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"{OUT}: {frame.width}x{frame.height}, {len(packed)} compressed bytes")


if __name__ == "__main__":
    main()
