"""Runs the Archipelago loop test bench (loop_test.exe) on a new seed.

    python mod/tests/run_loop_test.py [Archipelago folder]

The Archipelago folder is either an installed Archipelago (ArchipelagoGenerate.exe, default
C:\\ProgramData\\Archipelago) or a source checkout (Generate.py, used by the CI). The installed
bioshock_infinite world is used: install it again after changing it (build.ps1 -Install).

1. takes the seed generated in the background by the previous run (each seed serves once), or
   generates one with tests/players/*.yaml (about 10 s: Archipelago loads every world);
2. starts a test Archipelago server on port 38282, and meanwhile generates the next run's seed (not
   on the CI, whose Archipelago is new each time);
3. connects a fake DeathLink player (slot Finder): it writes down each death of Booker received
   and answers with its own;
4. runs loop_test.exe (built by build.ps1, or: cmake --build mod/build --config Release --target loop_test);
5. stops everything. Exit code: the test's.

A seed generated in advance is only used with the same apworld, players and Archipelago.

Needs the "websockets" Python package (pip install websockets).
"""

import asyncio
import glob
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import threading
import time

import websockets

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
# Absolute: the Archipelago tools run with it as working directory (the CI passes a relative path).
ARCHIPELAGO = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else r"C:\ProgramData\Archipelago")
PORT = 38282
TEST_EXE = os.path.join(ROOT, "mod", "bin", "tests", "Release", "loop_test.exe")
MACHINES = os.path.join(ROOT, "apworld", "bioshock_infinite", "machines.py")
PLAYERS = os.path.join(HERE, "players")
# The next run's seed: generated into PENDING, moved to READY once complete.
NEXT_SEED = os.path.join(tempfile.gettempdir(), "bsap_looptest_next_seed")
PENDING = os.path.join(NEXT_SEED, "pending")
READY = os.path.join(NEXT_SEED, "ready")


def archipelago_command(tool: str) -> list[str]:
    """Command line of an Archipelago tool (Generate, Server): installed exe or source script."""
    exe = os.path.join(ARCHIPELAGO, f"Archipelago{tool}.exe")
    if os.path.exists(exe):
        return [exe]
    script = {"Generate": "Generate.py", "Server": "MultiServer.py"}[tool]
    return [sys.executable, os.path.join(ARCHIPELAGO, script)]


def seed_key() -> str:
    """What a seed depends on: the installed world, the players and the Archipelago version."""
    h = hashlib.sha256()
    world = os.path.join(ARCHIPELAGO, "custom_worlds", "bioshock_infinite.apworld")
    paths = [world] + sorted(glob.glob(os.path.join(PLAYERS, "*.yaml")))
    for path in paths:
        h.update(path.encode())
        if os.path.exists(path):
            with open(path, "rb") as f:
                h.update(f.read())
    tool = archipelago_command("Generate")[-1]
    h.update(f"{tool} {os.path.getsize(tool)} {os.path.getmtime(tool)}".encode())
    return h.hexdigest()


def generate(outdir: str, background: bool = False):
    """Runs Archipelago's Generate into outdir: its result, or its Popen when in the background."""
    command = archipelago_command("Generate") + [f"--player_files_path={PLAYERS}", f"--outputpath={outdir}"]
    if background:
        return subprocess.Popen(command, cwd=ARCHIPELAGO, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    return subprocess.run(
        command, cwd=ARCHIPELAGO, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, errors="replace"
    )


def take_ready_seed(work: str, key: str) -> bool:
    """Moves the seed generated by the previous run into work, if it matches key."""
    try:
        with open(os.path.join(READY, "key.txt"), encoding="utf-8") as f:
            ok = f.read() == key
        zips = glob.glob(os.path.join(READY, "AP_*.zip"))
        if ok and len(zips) == 1:
            shutil.move(zips[0], work)
            return True
    except OSError:
        pass
    finally:
        shutil.rmtree(READY, ignore_errors=True)  # one run per seed
    return False


def start_next_seed():
    """Generates the next run's seed in the background (Popen), or None on the CI."""
    if os.environ.get("CI"):
        return None
    shutil.rmtree(PENDING, ignore_errors=True)  # left by an interrupted run
    os.makedirs(PENDING)
    return generate(PENDING, background=True)


def finish_next_seed(process, key: str) -> None:
    """Waits for the background generation and makes its seed ready for the next run."""
    if process is None:
        return
    try:
        if process.wait(timeout=120) == 0 and len(glob.glob(os.path.join(PENDING, "AP_*.zip"))) == 1:
            with open(os.path.join(PENDING, "key.txt"), "w", encoding="utf-8") as f:
                f.write(key)
            shutil.rmtree(READY, ignore_errors=True)
            os.replace(PENDING, READY)
    except (subprocess.TimeoutExpired, OSError):
        process.kill()


async def deathlink_player(log_path: str, stop: threading.Event) -> None:
    """The Finder slot, subscribed to DeathLink: writes down Booker's deaths and sends its own back."""
    async with websockets.connect(f"ws://localhost:{PORT}", max_size=None) as ws:
        await ws.recv()  # RoomInfo
        await ws.send(
            json.dumps(
                [
                    {
                        "cmd": "Connect",
                        "game": "ChecksFinder",
                        "name": "Finder",
                        "password": "",
                        "uuid": "looptest-finder",
                        "items_handling": 0,
                        "tags": ["DeathLink"],
                        "version": {"major": 0, "minor": 6, "build": 7, "class": "Version"},
                        "slot_data": False,
                    }
                ]
            )
        )
        while not stop.is_set():
            try:
                packets = json.loads(await asyncio.wait_for(ws.recv(), 0.5))
            except TimeoutError:
                continue
            for p in packets:
                data = p.get("data", {})
                if p.get("cmd") == "Bounced" and "DeathLink" in p.get("tags", []) and data.get("source") == "Booker":
                    with open(log_path, "a", encoding="utf-8") as f:
                        f.write(data.get("cause", "") + "\n")
                    await asyncio.sleep(0.05)  # the test waits in real time for this answer
                    await ws.send(
                        json.dumps(
                            [
                                {
                                    "cmd": "Bounce",
                                    "tags": ["DeathLink"],
                                    "data": {
                                        "time": time.time(),
                                        "source": "Finder",
                                        "cause": "Finder clicked a bomb.",
                                    },
                                }
                            ]
                        )
                    )


def main() -> int:
    if not os.path.exists(TEST_EXE):
        print(f"{TEST_EXE} not found: build the loop_test target first.")
        return 2
    work = tempfile.mkdtemp(prefix="bsap_looptest_")
    code = run(work)
    if code == 0:
        shutil.rmtree(work, ignore_errors=True)
    else:
        print(f"The seed and the server log are kept in {work}")
    return code


def run(work: str) -> int:
    """Gets a seed into work, starts the server and the fake player, runs the test."""
    key = seed_key()
    if not take_ready_seed(work, key):
        result = generate(work)
        if result.returncode != 0:
            print(result.stdout)
            print(f"The seed generation failed (exit code {result.returncode}).")
            return 2
    multidata = glob.glob(os.path.join(work, "AP_*.zip"))[0]
    next_seed = start_next_seed()
    try:
        return serve_and_test(work, multidata)
    finally:
        finish_next_seed(next_seed, key)


def serve_and_test(work: str, multidata: str) -> int:
    """Starts the server and the fake player on multidata, runs the test."""
    server_log_path = os.path.join(work, "server.txt")
    with open(server_log_path, "w", encoding="utf-8", errors="replace") as server_log:
        server = subprocess.Popen(
            # --host: without it the server looks up the public IP online before listening.
            archipelago_command("Server") + ["--host", "localhost", "--port", str(PORT), multidata],
            cwd=ARCHIPELAGO,
            stdin=subprocess.PIPE,
            stdout=server_log,
            stderr=subprocess.STDOUT,
        )
        try:
            for _ in range(1200):  # the server loads every world before listening (about 10 s)
                time.sleep(0.1)
                with open(server_log_path, encoding="utf-8", errors="replace") as f:
                    if "server listening" in f.read():
                        break
                if server.poll() is not None:
                    break
            if server.poll() is not None:  # e.g. port already taken: we would test another server
                print(f"The test server didn't start (port {PORT} already taken?). See {server_log_path}")
                return 2
            death_log = os.path.join(work, "deathlink.txt")
            open(death_log, "w").close()
            # Lines the test appends to this file: commands for the server console.
            server_cmds = os.path.join(work, "server_cmds.txt")
            open(server_cmds, "w").close()

            def forward_commands() -> None:
                done = 0
                while server.poll() is None:
                    with open(server_cmds, encoding="utf-8") as f:
                        lines = f.read().splitlines()
                    for line in lines[done:]:
                        server.stdin.write((line + "\n").encode())
                        server.stdin.flush()
                    done = len(lines)
                    time.sleep(0.05)

            threading.Thread(target=forward_commands, daemon=True).start()
            stop = threading.Event()
            player = threading.Thread(target=lambda: asyncio.run(deathlink_player(death_log, stop)), daemon=True)
            player.start()
            try:
                return subprocess.run(
                    [TEST_EXE, f"Booker@localhost:{PORT}", MACHINES, server_log_path, death_log, server_cmds]
                ).returncode
            finally:
                stop.set()
                player.join(5)
        finally:
            server.kill()


if __name__ == "__main__":
    sys.exit(main())
